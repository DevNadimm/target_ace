CREATE INDEX IF NOT EXISTS idx_profiles_target_niche ON public.profiles (target_niche_id);
CREATE INDEX IF NOT EXISTS idx_exams_niche ON public.exams (niche_id);
CREATE INDEX IF NOT EXISTS idx_questions_exam ON public.questions (exam_id);
CREATE INDEX IF NOT EXISTS idx_user_answers_attempt ON public.user_answers (attempt_id);
CREATE INDEX IF NOT EXISTS idx_user_answers_question ON public.user_answers (question_id);
CREATE INDEX IF NOT EXISTS idx_subscriptions_user ON public.subscriptions (user_id);


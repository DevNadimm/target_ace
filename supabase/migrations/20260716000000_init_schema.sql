CREATE INDEX IF NOT EXISTS idx_exam_attempts_leaderboard 
ON public.exam_attempts (exam_id, disqualified, score DESC, time_taken_seconds ASC);

-- Index user_id on attempts for fast personal history retrieval
CREATE INDEX IF NOT EXISTS idx_exam_attempts_user_id 
ON public.exam_attempts (user_id);


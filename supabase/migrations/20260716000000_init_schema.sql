-- target_niches policies
CREATE POLICY "Allow read target_niches for authenticated users" 
ON public.target_niches FOR SELECT TO authenticated USING (TRUE);

CREATE POLICY "Allow admin manage target_niches" 
ON public.target_niches FOR ALL TO authenticated USING (public.is_admin());

-- profiles policies
CREATE POLICY "Allow users read own profile or admin read all" 
ON public.profiles FOR SELECT TO authenticated 
USING (auth.uid() = id OR public.is_admin());

CREATE POLICY "Allow users update own profile or admin update all" 
ON public.profiles FOR UPDATE TO authenticated 
USING (auth.uid() = id OR public.is_admin())
WITH CHECK (
    (auth.uid() = id AND is_admin = (SELECT is_admin FROM public.profiles WHERE id = auth.uid()) AND is_premium = (SELECT is_premium FROM public.profiles WHERE id = auth.uid()))
    OR public.is_admin()
);

-- exams policies
CREATE POLICY "Allow read published exams for authenticated or all for admin" 
ON public.exams FOR SELECT TO authenticated 
USING (is_published = TRUE OR public.is_admin());

CREATE POLICY "Allow admin manage exams" 
ON public.exams FOR ALL TO authenticated USING (public.is_admin());

-- questions policies (Prevents cheating by locking questions until 60 seconds before exam start)
CREATE POLICY "Allow select questions when exam is starting or admin" 
ON public.questions FOR SELECT TO authenticated 
USING (
    public.is_admin()
    OR
    EXISTS (
        SELECT 1 FROM public.exams 
        WHERE exams.id = questions.exam_id 
        AND exams.is_published = TRUE
        AND NOW() >= exams.start_time - INTERVAL '60 seconds'
    )
);

CREATE POLICY "Allow admin manage questions" 
ON public.questions FOR ALL TO authenticated USING (public.is_admin());

-- exam_attempts policies
CREATE POLICY "Allow read own attempt or any attempt for leaderboard/admin" 
ON public.exam_attempts FOR SELECT TO authenticated 
USING (
    user_id = auth.uid() 
    OR public.is_admin()
    OR EXISTS (
        SELECT 1 FROM public.exams 
        WHERE exams.id = exam_attempts.exam_id 
        AND exams.is_published = TRUE
    )
);

CREATE POLICY "Allow insert own attempt" 
ON public.exam_attempts FOR INSERT TO authenticated 
WITH CHECK (user_id = auth.uid());

CREATE POLICY "Allow update own attempt during active exam window" 
ON public.exam_attempts FOR UPDATE TO authenticated 
USING (user_id = auth.uid() OR public.is_admin())
WITH CHECK (
    (
        user_id = auth.uid() 
        AND EXISTS (
            SELECT 1 FROM public.exams 
            WHERE exams.id = exam_attempts.exam_id 
            -- Check that the current time is within the exam window (duration + 5 mins network grace period)
            AND NOW() >= exams.start_time - INTERVAL '60 seconds'
            AND NOW() <= exams.start_time + (exams.duration_minutes * INTERVAL '1 minute') + INTERVAL '5 minutes'
        )
    )
    OR public.is_admin()
);

-- user_answers policies
CREATE POLICY "Allow read own answers" 
ON public.user_answers FOR SELECT TO authenticated 
USING (
    EXISTS (
        SELECT 1 FROM public.exam_attempts 
        WHERE exam_attempts.id = user_answers.attempt_id 
        AND exam_attempts.user_id = auth.uid()
    )
    OR public.is_admin()
);

CREATE POLICY "Allow insert own answers" 
ON public.user_answers FOR INSERT TO authenticated 
WITH CHECK (
    EXISTS (
        SELECT 1 FROM public.exam_attempts 
        WHERE exam_attempts.id = attempt_id 
        AND exam_attempts.user_id = auth.uid()
    )
);

-- subscriptions policies
CREATE POLICY "Allow read own subscriptions or admin read all" 
ON public.subscriptions FOR SELECT TO authenticated 
USING (user_id = auth.uid() OR public.is_admin());

CREATE POLICY "Allow insert own subscriptions" 
ON public.subscriptions FOR INSERT TO authenticated 
WITH CHECK (user_id = auth.uid() AND status = 'pending');

CREATE POLICY "Allow admin update subscriptions" 
ON public.subscriptions FOR UPDATE TO authenticated 
USING (public.is_admin());
